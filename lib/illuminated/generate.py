"""Files derived from the resolved configuration.

Everything here is written under ~/.config/illuminated/generated/ and is safe to
delete; `illuminated apply` recreates it. Compositor syntax follows the
project's v2 integration examples and, for Mango, its configuration docs
(https://mangowm.github.io/docs/configuration/basics). Neither is run-verified yet:
  Hyprland 0.57 Lua: hl.on("hyprland.start", …), hl.exec_cmd, hl.bind, hl.dsp.exec_cmd, hl.config
  Mango 0.18:        exec_once=, bind=MODS,key,spawn,cmd, focus_color=, border_color=
"""
from __future__ import annotations

import shlex

from .config import parse_chord

REPEATING = ("volume up", "volume down", "brightness up", "brightness down")
HEADER = "Generated by `illuminated apply` from ~/.config/illuminated/config.toml. Do not edit."


def _lua(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _command(launcher: str, action: str) -> str:
    return " ".join([shlex.quote(launcher), *action.split()])


def _palette(values):
    return values["palettes"][values["appearance"]["mode"]]


def _rgb(colour: str) -> str:
    return colour[1:7].lower()


def binds(values):
    if not values["integration"]["binds"]:
        return []
    return [(chord, action) for chord, action in values["binds"].items() if action]


def hyprland(values, launcher: str) -> str:
    lines = ["-- " + HEADER, ""]
    if values["integration"]["autostart"]:
        lines += ['hl.on("hyprland.start", function()',
                  f"    hl.exec_cmd({_lua(_command(launcher, 'start'))})",
                  "end)", ""]
    for chord, action in binds(values):
        mods, key = parse_chord(chord)
        options = ", { repeating = true }" if action in REPEATING else ""
        lines.append(f"hl.bind({_lua(' + '.join([*mods, key]))}, "
                     f"hl.dsp.exec_cmd({_lua(_command(launcher, action))}){options})")
    if values["integration"]["borders"]:
        p = _palette(values)
        lines += ["", "hl.config({ general = { col = {",
                  f'    active_border = "rgba({_rgb(p["focusCore"])}ff)",',
                  f'    inactive_border = "rgba({_rgb(p["edge"])}ff)",',
                  "} } })"]
    return "\n".join(lines) + "\n"


def _mango_key(key: str) -> str:
    return key.lower() if len(key) == 1 or key.upper() == "SPACE" else key


def mango(values, launcher: str) -> str:
    lines = ["# " + HEADER, ""]
    if values["integration"]["autostart"]:
        lines += [f"exec_once={_command(launcher, 'start')}", ""]
    for chord, action in binds(values):
        mods, key = parse_chord(chord)
        lines.append(f"bind={'+'.join(mods) or 'NONE'},{_mango_key(key)},spawn,{_command(launcher, action)}")
    if values["integration"]["borders"]:
        p = _palette(values)
        lines += ["", f"focus_color=0x{_rgb(p['focusCore'])}ff", f"border_color=0x{_rgb(p['edge'])}ff"]
    return "\n".join(lines) + "\n"


def terminal_themes(values) -> dict[str, str]:
    p = _palette(values)
    rgb = {k: _rgb(v) for k, v in p.items()}
    return {
        "foot.ini": "# " + HEADER + "\n[colors]\n"
                    f"background={rgb['paper']}\nforeground={rgb['ink']}\n"
                    f"selection-background={rgb['activePaper']}\nselection-foreground={rgb['ink']}\n",
        "kitty.conf": "# " + HEADER + "\n"
                      f"background #{rgb['paper']}\nforeground #{rgb['ink']}\n"
                      f"selection_background #{rgb['activePaper']}\nselection_foreground #{rgb['ink']}\n",
        "gtk.css": "/* " + HEADER + " Symbolic colours only; support varies by toolkit. */\n" + "".join(
            f"@define-color {name} #{rgb[key]};\n" for name, key in
            [("theme_bg_color", "paper"), ("theme_fg_color", "ink"),
             ("theme_selected_bg_color", "activePaper"), ("theme_selected_fg_color", "ink")]),
    }


def everything(values, launcher: str) -> dict[str, str]:
    return {"hyprland.lua": hyprland(values, launcher), "mango.conf": mango(values, launcher),
            **terminal_themes(values)}
